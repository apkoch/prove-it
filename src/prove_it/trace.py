"""trace: every Must and Should requirement has a test that passed in this run.

Runs the suite with results recording on (the pytest plugin enforces that every test cites known
requirements), then checks coverage and writes the traceability matrix to
.prove-it/traceability.md.
"""

import json
import os
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

from prove_it import requirements
from prove_it.config import Config
from prove_it.requirements import Requirement


def run_suite(cfg: Config) -> tuple[int, dict[str, dict[str, object]]]:
    fd, name = tempfile.mkstemp(suffix=".json")
    os.close(fd)
    out = Path(name)
    done = subprocess.run(
        [*cfg.test_command, "-q"], cwd=cfg.root, env={**os.environ, "PROVE_IT_RESULTS": str(out)}
    )
    raw = json.loads(out.read_text()) if out.stat().st_size else {}
    out.unlink()
    return done.returncode, raw


def coverage(
    reqs: dict[str, Requirement], results: dict[str, dict[str, object]]
) -> tuple[list[tuple[Requirement, str]], list[str]]:
    """Each requirement's status, and the problems that fail the check."""
    tests_by_req: defaultdict[str, list[bool]] = defaultdict(list)
    for row in results.values():
        for r in row["reqs"]:  # type: ignore[union-attr]
            tests_by_req[str(r)].append(row["outcome"] == "passed")
    rows: list[tuple[Requirement, str]] = []
    problems: list[str] = []
    for r in reqs.values():
        tests = tests_by_req.get(r.id, [])
        passing = sum(tests)
        if r.retired:
            status = "retired"
        elif passing:
            status = f"{passing} passing"
        elif tests:
            status = "FAILING"
        else:
            status = "no test"
        if r.due and status in ("FAILING", "no test"):
            problems.append(f"{r.id} (priority {r.priority}): {status}")
        rows.append((r, status))
    return rows, problems


def write_matrix(cfg: Config, rows: list[tuple[Requirement, str]]) -> Path:
    lines = [
        "# Traceability matrix",
        "",
        "Generated by `prove-it trace`. Do not edit.",
        "",
        "| Requirement | Priority | Status | Text |",
        "|---|---|---|---|",
    ]
    lines += [f"| {r.id} | {r.priority} | {status} | {r.text} |" for r, status in rows]
    target = cfg.root / ".prove-it" / "traceability.md"
    target.parent.mkdir(exist_ok=True)
    target.write_text("\n".join(lines) + "\n")
    return target


def main(cfg: Config) -> int:
    reqs = requirements.load(cfg.requirements)
    if not reqs:
        print(f"trace FAILED: no requirements found in {cfg.requirements}", file=sys.stderr)
        return 1
    code, results = run_suite(cfg)
    if not results:
        print("trace FAILED: the suite recorded no results (see pytest's output)", file=sys.stderr)
        return 1
    rows, problems = coverage(reqs, results)
    matrix = write_matrix(cfg, rows)
    if code != 0:
        problems.insert(0, f"the suite failed (exit {code})")
    if problems:
        print("trace FAILED:\n- " + "\n- ".join(problems), file=sys.stderr)
        return 1
    due = sum(1 for r in reqs.values() if r.due)
    print(f"trace passed: {due} due requirements covered. Matrix: {matrix.relative_to(cfg.root)}")
    return 0
